export function t(path, vars) {
  const parts = path.split('.');
  let cur = ID;
  for (const p of parts) {
    if (cur == null) return path;
    cur = cur[p];
  }
  if (typeof cur !== 'string') return cur ?? path;
  return vars ? cur.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? vars[k] : `{${k}}`)) : cur;
}

// Format angka Indonesia: 24.000, 73,3%
export function fmtNumber(x, decimals = 0) {
  if (x == null || !isFinite(x)) return '—';
  return x.toLocaleString('id-ID', { minimumFractionDigits: decimals, maximumFractionDigits: decimals });
}

export function fmtPercent(x, decimals = 1) {
  if (x == null || !isFinite(x)) return '—';
  return fmtNumber(x * 100, decimals) + '%';
}

export function fmtLiter(x) {
  return x == null ? '—' : `${fmtNumber(x)} liter`;
}
